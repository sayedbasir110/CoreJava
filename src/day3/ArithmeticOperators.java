package day3;

public class ArithmeticOperators {
    public static void main(String[] args){
        int num1=20;
        int num2=10;

        int sum=num1+num2;  //Addition
        int dis=num1-num2;  //Distraction
        int mul=num1*num2;  //Multiplication
        int div=num1/num2;  // Division
        int rmndr=num1%num2;    // remainder

        System.out.println("sum of num1 and num2:"+sum);
        System.out.println("Distraction of num1 and num2:"+dis);
        System.out.println("Multiplication of num1 and num2:"+mul);
        System.out.println("Division of num1 and num2:"+div);
        System.out.println("Modulus of num1 and num2:"+rmndr);
    }
}
